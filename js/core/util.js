  function shuffle(arr) {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  }

  /** Mischt so lange, bis die Reihenfolge nicht mehr der Ausgangsreihenfolge entspricht. */
  function shuffleNotIdentity(arr) {
    if (arr.length < 2) return arr.slice();
    let a;
    do a = shuffle(arr); while (a.every((x, i) => x === arr[i]));
    return a;
  }

  const sample = (arr, n) => shuffle(arr).slice(0, n);
  const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));

  /** Stabiler Kurz-Hash (djb2) – für Karten-IDs aus Text. */
  function hash(str) {
    let h1 = 5381;
    for (let i = 0; i < str.length; i++) h1 = ((h1 << 5) + h1 + str.charCodeAt(i)) | 0;
    return (h1 >>> 0).toString(36);
  }

  function slug(str) {
    return String(str)
      .toLowerCase()
      .replace(/ä/g, 'ae').replace(/ö/g, 'oe').replace(/ü/g, 'ue').replace(/ß/g, 'ss')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
  }

  // Datumsangaben immer als lokales 'YYYY-MM-DD'
  function dateStr(d) {
    const p = (n) => String(n).padStart(2, '0');
    return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
  }
  const today = () => dateStr(new Date());
  function addDays(str, n) {
    const [y, m, d] = str.split('-').map(Number);
    return dateStr(new Date(y, m - 1, d + n));
  }
  function daysBetween(a, b) {
    const [y1, m1, d1] = a.split('-').map(Number);
    const [y2, m2, d2] = b.split('-').map(Number);
    return Math.round((new Date(y2, m2 - 1, d2) - new Date(y1, m1 - 1, d1)) / 86400000);
  }

  function plural(n, one, many) {
    return `${n} ${n === 1 ? one : many}`;
  }

  function formatTime(ms) {
    const sec = Math.round(ms / 1000);
    const m = Math.floor(sec / 60);
    return m ? `${m}:${String(sec % 60).padStart(2, '0')} min` : `${sec} s`;
  }

