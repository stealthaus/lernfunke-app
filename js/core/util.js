  function isChild(x) {
    return x == null || x === false || typeof x === 'string' || typeof x === 'number' || Array.isArray(x) || x instanceof Node;
  }

  function append(el, children) {
    for (const c of children) {
      if (c == null || c === false) continue;
      if (Array.isArray(c)) append(el, c);
      else el.appendChild(c instanceof Node ? c : document.createTextNode(String(c)));
    }
  }

  function setAttrs(el, attrs, svg) {
    for (const [k, v] of Object.entries(attrs)) {
      if (v == null || v === false) continue;
      if (k === 'class') svg ? el.setAttribute('class', v) : (el.className = v);
      else if (k === 'style' && typeof v === 'object') {
        // CSS-Variablen (--x) gehen nur über setProperty
        for (const [p, val] of Object.entries(v)) p.startsWith('--') ? el.style.setProperty(p, val) : (el.style[p] = val);
      }
      else if (k === 'html') el.innerHTML = v;
      else if (k === 'dataset') Object.assign(el.dataset, v);
      else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v);
      else if (v === true) el.setAttribute(k, '');
      else el.setAttribute(k, v);
    }
  }

  /** HTML-Element bauen: h('button', {class: 'btn', onclick: fn}, 'Text', kindElement) */
  function h(tag, attrs, ...children) {
    const el = document.createElement(tag);
    if (isChild(attrs)) children.unshift(attrs);
    else if (attrs) setAttrs(el, attrs, false);
    append(el, children);
    return el;
  }

  /** SVG-Element bauen (gleiche Signatur wie h). */
  function s(tag, attrs, ...children) {
    const el = document.createElementNS('http://www.w3.org/2000/svg', tag);
    if (isChild(attrs)) children.unshift(attrs);
    else if (attrs) setAttrs(el, attrs, true);
    append(el, children);
    return el;
  }

